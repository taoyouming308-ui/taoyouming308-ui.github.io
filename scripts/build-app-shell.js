#!/usr/bin/env node
const fs = require('node:fs');
const crypto = require('node:crypto');
const paths = require('./app-shell-files.json');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const version = Number(fs.readFileSync('version.txt', 'utf8'));
const types = { html: ['text/html'], js: ['text/javascript', 'application/javascript'], css: ['text/css'], json: ['application/json'], png: ['image/png'] };
const htmlSources = ['perm-app.html', 'frontdesk.html', 'operations.html'].map(p => fs.readFileSync(p, 'utf8')).join('\n');
for (const entry of ['perm-app.html', 'frontdesk.html', 'operations.html']) {
  const html = fs.readFileSync(entry, 'utf8');
  if (!html.includes('data-version="' + version + '"')) throw new Error('Entry version mismatch: ' + entry);
  for (const match of html.matchAll(/(?:src|href)=["']([\w.-]+\.(?:js|css))(?:\?[^"']*)?["']/g)) {
    if (!paths.includes(match[1])) throw new Error('Static dependency missing from reviewed allowlist: ' + match[1]);
  }
}
for (const manifest of ['manifest.json','frontdesk-manifest.json']) {
  for (const icon of JSON.parse(fs.readFileSync(manifest,'utf8')).icons || []) {
    if (!paths.includes(icon.src)) throw new Error('Manifest icon missing: ' + icon.src);
  }
}
const files = paths.map(path => {
  if (!/^[\w.-]+\.(html|js|css|json|png)$/.test(path) || !types[path.split('.').pop()]) throw new Error('Not a reviewed root public asset: ' + path);
  const versions = new Set([String(version)]);
  for (const match of htmlSources.matchAll(/(?:src|href)=["']([^"']+)\?v=(\d+)/g)) if (match[1] === path) versions.add(match[2]);
  return { path, sha256: hash(fs.readFileSync(path)), types: types[path.split('.').pop()], versions: [...versions] };
});
const runtime = fs.readFileSync('scripts/app-shell-worker-runtime.js', 'utf8');
const config = { version, id: hash(JSON.stringify(files) + runtime).slice(0, 16), files };
const output = '// Generated by node scripts/build-app-shell.js. Do not edit.\nconst SHELL = ' + JSON.stringify(config, null, 2) + ';\n' + runtime;
if (process.argv.includes('--check')) {
  if (fs.readFileSync('app-shell-sw.js', 'utf8') !== output) throw new Error('Stale static shell: run node scripts/build-app-shell.js');
  console.log('static shell manifest verified: v' + version + ', ' + files.length + ' explicit public files');
} else {
  fs.writeFileSync('app-shell-sw.js', output);
  console.log('generated static shell v' + version + ', ' + files.length + ' files');
}

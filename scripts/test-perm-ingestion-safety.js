'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const { build, validate, parseBatch, shanghaiDate, retryTransient, importFeed, restoreFeed, preflightBatch } = require('./build-perm-academy-feed');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const original = JSON.parse(fs.readFileSync('docs/perm/academy-feed.v1.json','utf8'));
const entry = original.items[0];
const clone = x => JSON.parse(JSON.stringify(x));
const transient = code => Object.assign(Error('synthetic transient IO'), { code });
async function run() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'perm-safety-fixtures-'));
  const input = path.join(dir,'reviewed.json'), output = path.join(dir,'feed.json'), recovery = path.join(dir,'private-recovery');
  const originalBytes = fs.readFileSync('docs/perm/academy-feed.v1.json');
  fs.writeFileSync(output,originalBytes);
  const options = { recoveryDir:recovery, retry:{ delayMs:0 } };
  const write = data => fs.writeFileSync(input,JSON.stringify(data));
  const bytes = () => fs.readFileSync(output);
  let cases = 0;
  assert.equal(shanghaiDate('2026-10-05T16:00:00Z'),'2026-10-06');
  assert.equal(shanghaiDate('2026-10-05T15:59:59Z'),'2026-10-05');
  assert.throws(() => shanghaiDate('2026-02-31T16:00:00Z'));
  assert.throws(() => shanghaiDate('2026-10-05T16:00:00'));
  cases += 4;
  const batch = { schemaVersion:1, batch:{ id:'perm-2026-10-06',producedAt:'2026-10-05T16:00:00Z',timezone:'Asia/Shanghai' }, items:[{...entry,batchDate:undefined}] };
  assert.equal(parseBatch(batch).items[0].batchDate,'2026-10-06');
  assert.throws(() => parseBatch({...batch,batch:{...batch.batch,id:'perm-2026-10-05'}}));
  assert.throws(() => parseBatch({...batch,items:[{...entry,batchDate:'2026-10-05'}]}));
  cases += 3;
  write([entry]);
  const oldMtime = fs.statSync(output).mtimeMs;
  const noOp = await importFeed(input,output,options);
  assert.equal(noOp.changed,false); assert(bytes().equals(originalBytes));
  assert.equal(fs.statSync(output).mtimeMs,oldMtime); assert(!fs.existsSync(recovery));
  cases += 4;
  write([{...entry,title:entry.title+'（新标题）',reviewedAt:'2026-10-07T10:00:00+08:00',reviewedBy:'重复核验 fixture',batchDate:'2026-10-07'}]);
  assert.equal((await importFeed(input,output,options)).changed,false);
  assert(bytes().equals(originalBytes)); cases += 2;
  const currentNormalized = validate(entry);
  assert.throws(() => validate({...entry,contentFingerprint:'not-the-fingerprint'}));
  assert.equal(currentNormalized.contentFingerprint,validate({...entry,source:{...entry.source,url:entry.source.url+'?utm_source=fixture#fragment'}}).contentFingerprint);
  assert.throws(() => validate({...entry,batchDate:'2026-02-31'}));
  assert.throws(() => validate({...entry,source:{...entry.source,publishedAt:'2026-02-31'}}));
  cases += 4;
  for (const invalid of [{...entry,reviewStatus:'pending'},{...entry,isRealCase:true,authorization:'unknown'},{...entry,isExample:true,evidence:{level:'强',basis:'fixture'}}]) {
    write([invalid]); await assert.rejects(importFeed(input,output,options)); assert(bytes().equals(originalBytes)); cases += 2;
  }
  const changed = {...entry,contentFingerprint:undefined,coreKnowledge:entry.coreKnowledge+'\n[仅临时测试：不可发布]',reviewedAt:'2026-10-07T10:00:00+08:00',batchDate:'2026-10-07'};
  assert.throws(() => build(original,[{...changed,reviewedAt:entry.reviewedAt}]));
  assert.strictEqual(build(original,[{...changed,reviewedAt:'2026-01-01T00:00:00Z'}]),original); cases += 2;
  write([changed]);
  let attempts = 0;
  const success = await importFeed(input,output,{...options,rename:(from,to) => { if (++attempts < 3) throw transient('EBUSY'); fs.renameSync(from,to); }});
  assert.equal(attempts,3); assert(success.changed); assert(fs.readFileSync(success.recovery).equals(originalBytes));
  const accepted = JSON.parse(bytes());
  assert.equal(accepted.items[0].id,entry.id); assert.equal(accepted.items[0].batchDate,entry.batchDate);
  assert(/^[a-f0-9]{64}$/.test(accepted.items[0].contentFingerprint));
  cases += 6;
  const beforeReplay = bytes(), replayMtime = fs.statSync(output).mtimeMs;
  assert.equal((await importFeed(input,output,options)).changed,false);
  assert(bytes().equals(beforeReplay)); assert.equal(fs.statSync(output).mtimeMs,replayMtime); cases += 3;
  write([{...changed,coreKnowledge:changed.coreKnowledge+' more fixture',reviewedAt:'2026-10-08T00:00:00Z'}]);
  attempts = 0;
  await assert.rejects(importFeed(input,output,{...options,rename:() => { attempts++; throw transient('ETIMEDOUT'); }}));
  assert.equal(attempts,3); assert(bytes().equals(beforeReplay)); assert(!fs.existsSync(output+'.lock'));
  assert(!fs.readdirSync(dir).some(name => name.endsWith('.tmp'))); cases += 4;
  attempts = 0;
  await assert.rejects(importFeed(input,output,{...options,rename:() => { attempts++; throw transient('EACCES'); }}));
  assert.equal(attempts,1); assert(bytes().equals(beforeReplay)); cases += 2;
  fs.writeFileSync(output+'.lock','existing owner fixture');
  await assert.rejects(importFeed(input,output,options));
  assert.equal(fs.readFileSync(output+'.lock','utf8'),'existing owner fixture'); assert(bytes().equals(beforeReplay));
  fs.unlinkSync(output+'.lock'); cases += 3;
  // Both imports race for one file; the second cannot enter while the first retries.
  let unblock;
  const blocked = new Promise(resolve => { unblock = resolve; });
  attempts = 0;
  const first = importFeed(input,output,{...options,retry:{delayMs:0,sleep:() => blocked},rename:(from,to) => {if (++attempts === 1) throw transient('EAGAIN');fs.renameSync(from,to);}});
  await assert.rejects(importFeed(input,output,options)); unblock(); const newest = await first;
  assert(newest.changed); assert(!fs.existsSync(output+'.lock')); cases += 2;
  await assert.rejects(restoreFeed(success.recovery,output,success.sha256,options)); cases++;
  const restored = await restoreFeed(success.recovery,output,newest.sha256,options);
  assert(restored.changed); assert(bytes().equals(originalBytes));
  assert.equal((await restoreFeed(success.recovery,output,sha(originalBytes),options)).changed,false);
  assert(!fs.existsSync(output+'.lock')); cases += 4;
  // A writer ignoring the lock is detected, and its newer content is never rolled back automatically.
  write([changed]);
  const external = Buffer.from(JSON.stringify({...original,updatedAt:'2030-01-01T00:00:00Z'})+'\n');
  attempts = 0;
  await assert.rejects(importFeed(input,output,{...options,retry:{delayMs:0,sleep:async() => {fs.writeFileSync(output,external);}},rename:() => {attempts++;throw transient('EBUSY');}}));
  assert.equal(attempts,1); assert(bytes().equals(external)); cases += 2;
  let slept = [];
  attempts = 0;
  await assert.rejects(retryTransient(() => {attempts++;throw transient('EBUSY');},{delayMs:800,sleep:async ms => slept.push(ms)}));
  assert.equal(attempts,3); assert.deepEqual(slept,[800,1000]);
  await assert.rejects(retryTransient(() => {},{attempts:4})); cases += 3;
  const zero = {schemaVersion:1,timezone:'Asia/Shanghai',updatedAt:null,items:[]};
  assert.strictEqual(build(zero,{...batch,items:[]}),zero); cases++;
  const pending = {...entry,reviewStatus:'pending',reviewedBy:null,reviewedAt:null};
  const metadataBatch = {...batch,batch:{...batch.batch,label:'基础精读',dailySummary:'fixture summary',lowRiskPractice:'clean water fixture only'},items:[pending]};
  const preflight = preflightBatch(metadataBatch);
  assert(preflight.preflightOnly && preflight.approvalRequired); assert.equal(preflight.items[0].reviewStatus,'pending');
  assert.equal(preflight.items[0].reviewedAt,null); assert.equal(preflight.batch.lowRiskPractice,'clean water fixture only');
  assert.throws(() => build(original,metadataBatch));
  assert.throws(() => preflightBatch({...metadataBatch,items:[{...pending,reviewedBy:'not approved'}]})); cases += 6;
  const rich = {...entry,contentFingerprint:undefined,source:{...entry.source,verifiedOn:'2026-10-06',updatedAt:'2026-08-31',onlinePublishedAt:'2015-02-08',dateNote:'updated vs initial'},evidence:{...entry.evidence,parts:[{type:'professional principle',level:'中',basis:'not experimental'}]}};
  const richNormalized = validate(rich);
  assert.equal(richNormalized.source.updatedAt,'2026-08-31');assert.equal(richNormalized.evidence.parts[0].level,'中');
  assert.equal(richNormalized.contentFingerprint,validate({...rich,source:{...rich.source,verifiedOn:'2026-10-07'}}).contentFingerprint);
  assert.throws(() => validate({...rich,source:{...rich.source,updatedAt:'2026-02-31'}})); cases += 4;
  const legacyTracked = {...entry,id:'legacy-learning-id',source:{...entry.source,url:entry.source.url+'?utm_source=legacy'}};
  const revisedLegacy = build({...original,items:[legacyTracked]},[{...changed,source:{...entry.source}}]);
  assert.equal(revisedLegacy.items.length,1);assert.equal(revisedLegacy.items[0].id,'legacy-learning-id');cases += 2;
  assert(fs.readFileSync('docs/perm/academy-feed.v1.json').equals(originalBytes)); cases++;
  console.log('perm ingestion safety passed: '+cases+' assertions; fixtures only in '+dir);
}
run().catch(error => {console.error(error);process.exitCode=1;});
